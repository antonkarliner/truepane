import fs from "node:fs";

const svgPath = new URL("../public/og-image.svg", import.meta.url);
const W = 220;
const H = 480;

function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function ringPattern() {
  const groups = [
    { cx: -0.08, cy: 0.3, baseR: 0.25, spacing: 0.065 },
    { cx: 0.86, cy: 0.22, baseR: 0.18, spacing: 0.06 },
    { cx: 0.78, cy: 0.76, baseR: 0.23, spacing: 0.065 },
  ];
  const shapes = [];
  for (const g of groups) {
    for (let k = 0; k < 4; k++) {
      shapes.push(
        `<circle cx="${(g.cx * W).toFixed(1)}" cy="${(g.cy * H).toFixed(1)}" r="${((g.baseR + k * g.spacing) * W).toFixed(1)}" fill="none" stroke="#1a1612" stroke-width="4" opacity="${(0.14 - k * 0.018).toFixed(3)}"/>`,
      );
    }
  }
  return shapes.join("\n      ");
}

function wavePattern() {
  const rng = mulberry32(41);
  const lines = 6;
  const shapes = [];
  for (let i = 0; i < lines; i++) {
    const baseY = 140 + i * 34;
    const amp = 13 + rng() * 15;
    const wl = 98 + rng() * 110;
    const phase = rng() * Math.PI * 2;
    const points = [];
    for (let x = -16; x <= W + 16; x += 10) {
      const y = baseY + Math.sin((x / wl) * Math.PI * 2 + phase) * amp;
      points.push(`${x === -16 ? "M" : "L"}${x.toFixed(1)} ${y.toFixed(1)}`);
    }
    shapes.push(
      `<path d="${points.join(" ")}" fill="none" stroke="#f0e4cc" stroke-width="6" stroke-linecap="round" opacity="${(0.46 - i * 0.03).toFixed(3)}"/>`,
    );
  }
  return shapes.join("\n      ");
}

function dotPattern() {
  const rng = mulberry32(123);
  const spacing = 30;
  const shapes = [];
  for (let y = 88; y < 360; y += spacing) {
    for (let x = 42; x < W; x += spacing) {
      const jx = (rng() - 0.5) * spacing * 0.45;
      const jy = (rng() - 0.5) * spacing * 0.45;
      shapes.push(
        `<circle cx="${(x + jx).toFixed(1)}" cy="${(y + jy).toFixed(1)}" r="4.6" fill="#f0e4cc" opacity="${(0.52 - rng() * 0.16).toFixed(3)}"/>`,
      );
    }
  }
  return shapes.join("\n      ");
}

const generated = `    <!-- Generated by scripts/generate-og-card-patterns.mjs. Mirrors render.ts shape families for the OG preview. -->
    <clipPath id="ogCardPatternClip">
      <rect x="16" y="16" width="188" height="448" rx="24"/>
    </clipPath>
    <g id="ogPatternRings">
      ${ringPattern()}
    </g>
    <g id="ogPatternWaves">
      ${wavePattern()}
    </g>
    <g id="ogPatternDots">
      ${dotPattern()}
    </g>`;

let svg = fs.readFileSync(svgPath, "utf8");
svg = svg.replace(
  /    <!-- Generated by scripts\/generate-og-card-patterns\.mjs[\s\S]*?    <\/g>\n  <\/defs>/,
  `${generated}\n  </defs>`,
);
if (!svg.includes("ogPatternRings")) {
  svg = svg.replace("  </defs>", `${generated}\n  </defs>`);
}
svg = svg
  .replace(
    /      <circle cx="50" cy="88"[\s\S]*?      <text x="40" y="82"/,
    '      <g clip-path="url(#ogCardPatternClip)">\n        <use href="#ogPatternRings"/>\n      </g>\n      <text x="40" y="82"',
  )
  .replace(
    /      <path d="M10 180[\s\S]*?      <text x="40" y="82"/,
    '      <g clip-path="url(#ogCardPatternClip)">\n        <use href="#ogPatternWaves"/>\n      </g>\n      <text x="40" y="82"',
  )
  .replace(
    /      <circle cx="56" cy="136"[\s\S]*?      <text x="40" y="82"/,
    '      <g clip-path="url(#ogCardPatternClip)">\n        <use href="#ogPatternDots"/>\n      </g>\n      <text x="40" y="82"',
  );

for (const patternId of ["ogPatternRings", "ogPatternWaves", "ogPatternDots"]) {
  svg = svg
    .replace(
      new RegExp(
        `      <g clip-path="url\\(#ogCardPatternClip\\)">\\n        <use href="#${patternId}"\\/>\\n      <\\/g>`,
        "g",
      ),
      `      <use href="#${patternId}"/>`,
    )
    .replace(
      new RegExp(`      <use href="#${patternId}"\\/>`, "g"),
      `      <g clip-path="url(#ogCardPatternClip)">\n        <use href="#${patternId}"/>\n      </g>`,
    );
}

fs.writeFileSync(svgPath, svg);
